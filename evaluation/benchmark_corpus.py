"""Measure index size and search time as the private corpus grows (synthetic texts).

Run: python evaluation/benchmark_corpus.py [--sizes 100 500 1000] [--words 6000] [--dir /tmp/x]
Writes evaluation/BENCHMARKS.md. Numbers depend on the machine; re-run on the
Railway engine service before choosing CORPUS_MAX_SOURCES.
"""
import argparse
import os
import platform
import random
import resource
import statistics
import string
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import corpus  # noqa: E402

os.environ["CORPUS_MAX_SOURCES"] = "1000000"


def pseudo_text(rng, words):
    """Random pseudo-words (3-10 letters) in sentences: realistic token diversity, no real content."""
    out = []
    for i in range(words):
        w = "".join(rng.choice(string.ascii_lowercase) for _ in range(rng.randint(3, 10)))
        out.append(w + ("." if i % 12 == 11 else ""))
    return " ".join(out)


def run(sizes, words, workdir):
    rng = random.Random(42)
    rows = []
    path = Path(workdir) / "bench.sqlite3"
    db = corpus.connect(path)
    texts, total, ingest_seconds = [], 0, 0.0
    for size in sizes:
        while total < size:
            text = pseudo_text(rng, words)
            texts.append(text) if len(texts) < 50 else None
            meta = dict(title=f"Synthetic {total}", url="https://example.org/s", language="en", authors="Bench",
                        year=2026, rights_basis="written_permission", permission_reference="synthetic")
            start = time.perf_counter()
            corpus.ingest(db, meta, text)
            ingest_seconds += time.perf_counter() - start
            total += 1
        size_mb = path.stat().st_size / 1e6
        # Manuscript: original filler plus three 50-word passages copied from indexed sources.
        planted = []
        for k in range(3):
            src = texts[k * 7 % len(texts)].split()
            pos = rng.randrange(0, len(src) - 50)
            planted.append(" ".join(src[pos:pos + 50]))
        manuscript = pseudo_text(rng, words // 3) + " " + " ".join(planted) + " " + pseudo_text(rng, words // 3)
        timings, found = [], 0
        for attempt in range(4):
            corpus._source_lexical.cache_clear() if attempt == 0 else None
            start = time.perf_counter()
            result = corpus.search(db, manuscript, "en")
            timings.append(time.perf_counter() - start)
            found = len(result["sources"])
        rows.append({"sources": size, "words_per_source": words, "db_mb": round(size_mb, 1),
                     "ingest_s_per_source": round(ingest_seconds / total, 3),
                     "search_cold_s": round(timings[0], 3), "search_warm_median_s": round(statistics.median(timings[1:]), 3),
                     "sources_found": found, "peak_rss_mb": round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024, 1)})
        print(rows[-1], flush=True)
    db.close()
    return rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", type=int, nargs="+", default=[100, 500, 1000])
    parser.add_argument("--words", type=int, default=6000)
    parser.add_argument("--dir", default=None)
    parser.add_argument("--out", type=Path, default=ROOT / "evaluation" / "BENCHMARKS.md")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(dir=args.dir) as tmp:
        rows = run(sorted(args.sizes), args.words, tmp)
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    lines = ["# Private corpus scaling benchmark", "", "Generated by `python evaluation/benchmark_corpus.py`. Do not edit by hand.", "",
             f"- Commit `{commit}` · Python {platform.python_version()} · {platform.machine()} · {os.cpu_count()} CPUs · "
             f"synthetic {args.words}-word sources (about one journal article each)",
             "- Manuscript: about 4,150 words containing three 50-word passages copied from three indexed sources. "
             "`Sources found` must be 3 at every size.",
             "- This machine is not the Railway engine; repeat the run there before raising `CORPUS_MAX_SOURCES`.", "",
             "| Indexed sources | Database size (MB) | Import time per source (s) | Search, first run (s) | Search, repeated (median s) | Sources found | Peak memory (MB) |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['sources']} | {r['db_mb']} | {r['ingest_s_per_source']} | {r['search_cold_s']} | "
                     f"{r['search_warm_median_s']} | {r['sources_found']} | {r['peak_rss_mb']} |")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
